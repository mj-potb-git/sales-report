// Generates supabase/seed.sql from the deterministic mock sales data.
// Run with: node scripts/generate-seed-sql.mjs

import { mockSalesRecords } from '../src/data/mockSalesData.js'
import { writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const out = resolve(__dirname, '../supabase/seed.sql')
mkdirSync(dirname(out), { recursive: true })

const esc = (s) => String(s).replace(/'/g, "''")

const header = `-- Auto-generated by scripts/generate-seed-sql.mjs
-- Drop + recreate sales_records, enable RLS, add a public-read policy,
-- then seed ${mockSalesRecords.length} rows.

drop table if exists public.sales_records;

create table public.sales_records (
  transaction_id text primary key,
  sales_agent    text not null,
  team           text not null,
  date           date not null,
  sales_amount   integer not null,
  signup_count   integer not null,
  customer_name  text not null,
  created_at     timestamptz not null default now()
);

create index sales_records_date_idx       on public.sales_records (date);
create index sales_records_agent_idx      on public.sales_records (sales_agent);
create index sales_records_team_idx       on public.sales_records (team);

-- Enable Row Level Security and allow anon/publishable-key reads
alter table public.sales_records enable row level security;

drop policy if exists "Allow public read" on public.sales_records;
create policy "Allow public read"
  on public.sales_records
  for select
  to anon, authenticated
  using (true);

-- Seed data
insert into public.sales_records
  (transaction_id, sales_agent, team, date, sales_amount, signup_count, customer_name) values
`

const values = mockSalesRecords.map(r =>
  `('${esc(r.transaction_id)}', '${esc(r.sales_agent)}', '${esc(r.team)}', '${r.date}', ${r.sales_amount}, ${r.signup_count}, '${esc(r.customer_name)}')`
).join(',\n')

writeFileSync(out, header + values + ';\n', 'utf8')

console.log(`wrote ${mockSalesRecords.length} rows to ${out}`)
